/** Build-time sampling of our authored, x-monotonic M/C SVG boundaries. */
import { readFile, writeFile } from 'node:fs/promises'
const source=new URL('../assets/motion/silk-ribbon.svg',import.meta.url)
const target=new URL('../src/client/effects/composer-ribbon-surface.generated.ts',import.meta.url)
const check=process.argv.includes('--check')
let svg=await readFile(source,'utf8')
function parse(id) {
  const d=svg.match(new RegExp(`<path id="${id}" d="([^"]+)"`))?.[1]
  if(!d)throw new Error(`Missing ${id}`)
  const tokens=d.match(/[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:e[-+]?\d+)?/g)||[]
  if(tokens[0]!=='M'||tokens.length!==31)throw new Error(`Unsupported boundary ${id}`)
  let p=[Number(tokens[1]),Number(tokens[2])],curves=[]
  for(let i=3;i<tokens.length;i+=7){
    if(tokens[i]!=='C')throw new Error(`Only M/C supported: ${id}`)
    const q=tokens.slice(i+1,i+7).map(Number)
    if(!q.every(Number.isFinite)||!(p[0]<q[0]&&q[0]<q[2]&&q[2]<q[4]))throw new Error(`Non-monotonic ${id}`)
    curves.push([p,[q[0],q[1]],[q[2],q[3]],[q[4],q[5]]]);p=[q[4],q[5]]
  }
  if(curves[0][0][0]!==0||p[0]!==1280)throw new Error(`Wrong extent ${id}`)
  return {d,curves}
}
const cubic=(c,t,axis)=>{const v=1-t;return v*v*v*c[0][axis]+3*v*v*t*c[1][axis]+3*v*t*t*c[2][axis]+t*t*t*c[3][axis]}
function sample(path,x){const c=path.curves.find(c=>x<=c[3][0])||path.curves.at(-1);let lo=0,hi=1;for(let i=0;i<32;i++){const t=(lo+hi)/2;if(cubic(c,t,0)<x)lo=t;else hi=t}return cubic(c,(lo+hi)/2,1)-160}
const values=[],fills=[]
for(let layer=0;layer<3;layer++){
  const upper=parse(`silk-${layer}-upper`),lower=parse(`silk-${layer}-lower`)
  for(const x of [0,1280])if(Math.abs(sample(upper,x)-sample(lower,x))>.001)throw new Error('Open ribbon endpoint')
  for(let i=0;i<=128;i++){const x=i*10;values.push(x/1280,sample(upper,x),x/1280,sample(lower,x))}
  const reverse=lower.curves.toReversed().map(c=>`C ${c[2].join(' ')} ${c[1].join(' ')} ${c[0].join(' ')}`).join(' ')
  fills.push(`  <path d="${upper.d} L ${lower.curves.at(-1)[3].join(' ')} ${reverse} Z" fill="url(#${layer===1?'coral':'blue'})"/>\n  <use href="#silk-${layer}-upper" stroke="url(#edge)" stroke-width="1.3"/>`)
}
const generated=`// Generated by tools/gen-silk-surface.mjs from assets/motion/silk-ribbon.svg.\n// Each vec4 is upper.xy / lower.xy, x normalized, y relative to 160.\nexport const silkSurfaceSamples = new Float32Array([\n${Array.from({length:values.length/4},(_,i)=>'  '+values.slice(i*4,i*4+4).map(v=>Number(v.toFixed(6))).join(',')+',').join('\n')}\n])\n`
const updated=svg.replace(/  <!-- surfaces:start -->[\s\S]*?  <!-- surfaces:end -->/,`  <!-- surfaces:start -->\n${fills.join('\n')}\n  <!-- surfaces:end -->`)
if(check){if(generated!==await readFile(target,'utf8')||updated!==svg)throw new Error('Silk SVG/data are stale');console.log('Silk SVG/data match')}
else{await writeFile(target,generated);await writeFile(source,updated);console.log('Generated 3 × 129 silk edge pairs')}
