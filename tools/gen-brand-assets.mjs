#!/usr/bin/env node
/**
 * Generate the inline brand artwork data from the source SVG.
 *
 * The browser half cannot read files, so the paths and badge geometry become a
 * TypeScript module. Run this after changing assets/deepseek-harness-logo-v2.svg.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const source = readFileSync(resolve(root, 'assets/deepseek-harness-logo-v2.svg'), 'utf8')
const output = resolve(root, 'src/client/brand/generated.tsx')

/**
 * Read one attribute from a serialized tag.
 *
 * @param tag - the tag text.
 * @param name - the attribute name.
 * @returns the attribute value, or an empty string.
 */
function attribute(tag, name) {
  const match = tag.match(new RegExp(`${name}="([^"]*)"`))
  return match?.[1] ?? ''
}

const paths = [...source.matchAll(/<path\b[^>]*>/g)].map((match) => match[0])
const whaleTag = paths.find((tag) => tag.includes('fill="#FF3B30"'))
const wordTags = paths.filter((tag) => tag.includes('fill="url(#dshWord)"'))
const badgeTags = paths.filter((tag) => tag.includes('dsh-badge-text'))

if (whaleTag === undefined) throw new Error('whale path not found')
if (wordTags.length === 0) throw new Error('wordmark paths not found')
if (badgeTags.length === 0) throw new Error('badge paths not found')

const whaleClip = source.match(/<clipPath id="dshWhaleClip">([\s\S]*?)<\/clipPath>/)?.[1] ?? ''
const whaleRectTag = whaleClip.match(/<rect\b[^>]*>/)?.[0] ?? ''
const badgeRectTag =
  source.match(/<rect\b[^>]*class="dsh-badge-fill"[^>]*>/)?.[0] ?? ''

if (whaleRectTag === '') throw new Error('whale clip rect not found')
if (badgeRectTag === '') throw new Error('badge rect not found')

const number = (tag, name) => Number(attribute(tag, name))

const lines = [
  '/**',
  ' * Generated by tools/gen-brand-assets.mjs. Do not edit by hand.',
  ' *',
  ' * Source: assets/deepseek-harness-logo-v2.svg',
  ' */',
  '',
  `export const WHALE_PATH = ${JSON.stringify(attribute(whaleTag, 'd'))}`,
  'export const WHALE_VIEWBOX = "28 29 52 41"',
  `export const WHALE_CLIP = ${JSON.stringify({
    x: number(whaleRectTag, 'x'),
    y: number(whaleRectTag, 'y'),
    width: number(whaleRectTag, 'width'),
    height: number(whaleRectTag, 'height'),
  })}`,
  '',
  'export const WORD_PATHS = [',
  ...wordTags.map((tag) => `  ${JSON.stringify(attribute(tag, 'd'))},`),
  '] as const',
  'export const WORD_VIEWBOX = "94 28 315 44"',
  '',
  `export const BADGE_RECT = ${JSON.stringify({
    x: number(badgeRectTag, 'x'),
    y: number(badgeRectTag, 'y'),
    width: number(badgeRectTag, 'width'),
    height: number(badgeRectTag, 'height'),
    rx: number(badgeRectTag, 'rx'),
  })}`,
  'export const BADGE_PATHS = [',
  ...badgeTags.map((tag) => `  ${JSON.stringify(attribute(tag, 'd'))},`),
  '] as const',
  '',
]

writeFileSync(output, lines.join('\n'), 'utf8')
console.log(`wrote ${output} (${wordTags.length} word paths, ${badgeTags.length} badge paths)`)
