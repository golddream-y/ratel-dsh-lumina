import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const source = new URL('../assets/session/session-cloud.svg', import.meta.url)
const target = new URL('../src/client/effects/session-cloud-art.generated.ts', import.meta.url)
const svg = await readFile(source, 'utf8')

const required = [
  'silhouette',
  'cool-depth',
  'warm-fold',
  'violet-fold',
  'inner-fold',
  'rim-outer',
  'rim-inner',
  'core-light',
  'halo-cool',
  'halo-warm',
]

if (!svg.includes('viewBox="0 0 128 128"')) throw new Error('Session cloud must use the 128x128 art viewport')
if (/<(?:script|foreignObject|image|use)\b/i.test(svg)) throw new Error('Unsupported session cloud element')
if (/href\s*=\s*["'](?!#)/i.test(svg)) throw new Error('Session cloud cannot reference external assets')

const paths = {}
for (const id of required) {
  const match = svg.match(new RegExp(`<path[^>]*\\sid="${id}"[^>]*\\sd="([^"]+)"`))
    ?? svg.match(new RegExp(`<path[^>]*\\sd="([^"]+)"[^>]*\\sid="${id}"`))
  if (!match) throw new Error(`Missing session cloud path: ${id}`)
  paths[id] = match[1]
}

const defs = svg.match(/<defs>([\s\S]*?)<\/defs>/)?.[1]
if (!defs) throw new Error('Missing session cloud materials')
const layers = {}
for (const id of required) {
  layers[id] = svg.match(new RegExp(`<path[^>]*\\sid="${id}"[^>]*/>`))?.[0]
  if (!layers[id]) throw new Error(`Missing layer: ${id}`)
}
const output = `// Generated by tools/gen-session-cloud-art.mjs. Edit assets/session/session-cloud.svg.
export const SESSION_CLOUD_PATHS = ${JSON.stringify(paths, null, 2)} as const
export const SESSION_CLOUD_DEFS = ${JSON.stringify(defs)}
export const SESSION_CLOUD_LAYERS = ${JSON.stringify(layers, null, 2)} as const
export type SessionCloudPathId = keyof typeof SESSION_CLOUD_PATHS
`

if (process.argv.includes('--check')) {
  if (output !== await readFile(target, 'utf8')) throw new Error('Session cloud artwork is stale')
  console.log('Session cloud artwork matches')
} else {
  await mkdir(dirname(fileURLToPath(target)), { recursive: true })
  await writeFile(target, output)
  console.log('Embedded session cloud artwork')
}
